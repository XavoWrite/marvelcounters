// busca la clave en el idioma actual, cae a español si falta (nunca deja un hueco visible),
// e interpola {variable} con los valores pasados en "vars"
function t(key, vars){
  let str = (I18N[currentLang] && I18N[currentLang][key]) ?? I18N.es[key] ?? key;
  if(vars) Object.keys(vars).forEach(k=>{ str = str.split(`{${k}}`).join(vars[k]); });
  return str;
}
// variante con pluralizacion: usa key+"_one" si n===1, si no key+"_other" -- cubre tanto el plural
// en "-s" del ingles como el "-es"/cambio de terminacion del espanol, cada idioma define el suyo
function tp(key, n, vars){
  return t(n===1 ? `${key}_one` : `${key}_other`, {n, ...vars});
}

// funciones que hay que volver a correr cuando cambia el idioma (re-renderizan desde el estado
// que ya existe, no lo resetean -- por eso no se pierden equipos ni nombres ya cargados)
const LANG_LISTENERS = [];
function onLangChange(fn){ LANG_LISTENERS.push(fn); }

function applyStaticTranslations(){
  document.querySelectorAll("[data-i18n]").forEach(el=>{ el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-html]").forEach(el=>{ el.innerHTML = t(el.dataset.i18nHtml); });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el=>{ el.placeholder = t(el.dataset.i18nPlaceholder); });
  document.querySelectorAll("[data-i18n-title]").forEach(el=>{ el.title = t(el.dataset.i18nTitle); });
}

function setLang(lang){
  currentLang = lang;
  try{ localStorage.setItem("lang", lang); }catch(e){}
  document.documentElement.lang = lang;
  document.querySelectorAll(".lang-btn").forEach(b=> b.classList.toggle("active", b.dataset.lang===lang));
  applyStaticTranslations();
  LANG_LISTENERS.forEach(fn=>{ try{ fn(); }catch(e){ console.error(e); } });
}

